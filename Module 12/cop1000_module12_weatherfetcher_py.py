import requests

print("Weather Forecast Fetcher\n")

city_name = input("Enter a city: ")

geo_url = "https://" + "geocoding-api." + "open-meteo.com" + "/v1/search"
geo_params = {
    "name": city_name,
    "count": 1,
    "language": "en",
    "format": "json"
}

geo_response = requests.get(geo_url, params=geo_params)

if geo_response.status_code == 200:
    geo_data = geo_response.json()

    if "results" in geo_data and len(geo_data["results"]) > 0:
        location = geo_data["results"][0]
        found_city = location["name"]
        region = location.get("admin1", location.get("country", ""))
        latitude = location["latitude"]
        longitude = location["longitude"]

        weather_url = "https://" + "api." + "open-meteo.com" + "/v1/forecast"
        weather_params = {
            "latitude": latitude,
            "longitude": longitude,
            "current": "temperature_2m,wind_speed_10m",
            "temperature_unit": "fahrenheit",
            "wind_speed_unit": "mph"
        }

        weather_response = requests.get(weather_url, params=weather_params)

        if weather_response.status_code == 200:
            weather_data = weather_response.json()
            current_weather = weather_data["current"]
            temperature = current_weather["temperature_2m"]
            wind_speed = current_weather["wind_speed_10m"]

            print(f"\nWeather for {found_city}, {region}\n")
            print(f"Temperature: {temperature} °F")
            print(f"Wind Speed: {wind_speed} mph")
        else:
            print("Error: Could not retrieve weather data.")
    else:
        print(f"Error: Could not find a location matching '{city_name}'.")
else:
    print("Error: Geocoding request was not successful.")