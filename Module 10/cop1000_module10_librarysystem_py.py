class Book:
    def __init__(self, title, author):
        self.title = title
        self.author = author
        self.availability = "Available"

    def display_info(self, index):
        print(f"{index}. {self.title} by {self.author} - {self.availability}")

    def check_out(self):
        self.availability = "Checked Out"

book1 = Book("Python Fundamentals", "A. Smith")
book2 = Book("Learning to Code", "J. Taylor")
book3 = Book("Programming Logic", "M. Jones")

library_books = [book1, book2, book3]

print("Library Catalog")
for idx, book in enumerate(library_books, start=1):
    book.display_info(idx)

print("\n" + "-"*40 + "\n")

book2.check_out()

print("Updated Library Catalog")
for idx, book in enumerate(library_books, start=1):
    book.display_info(idx)