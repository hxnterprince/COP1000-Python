import csv

print("Activity Data Logger\n")

activity1 = input("Enter activity 1: ")
minutes1 = input("Minutes: ")

activity2 = input("Enter activity 2: ")
minutes2 = input("Minutes: ")

activity3 = input("Enter activity 3: ")
minutes3 = input("Minutes: ")

with open("activity_log.csv", "w", newline="") as file:
    writer = csv.writer(file)

    writer.writerow(["Activity", "Minutes"])

    writer.writerow([activity1, minutes1])

    writer.writerow([activity2, minutes2])

    writer.writerow([activity3, minutes3])

print("\nData saved successfully.")
print("\n ===== Saved Activity Log =====")

with open("activity_log.csv", "r") as file:
    reader = csv.reader(file)

    next(reader)

    for row in reader:
        if len(row) >= 2:
            print(f"Activity: {row[0]}: Minutes: {row[1]}")